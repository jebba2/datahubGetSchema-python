-- Data set: Rubric Assessment (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4535-rubrics-data-sets#rubric-assessment
CREATE TABLE "RUBRIC_ASSESSMENT_LOAD" (
    "RUBRICID" NUMBER(19),
    "ORGUNITID" NUMBER(10),
    "USERID" NUMBER(10) NOT NULL,
    "SCORE" NUMBER(36,2),
    "ASSESSEDBYUSERID" NUMBER(10),
    "ASSESSMENTDATE" TIMESTAMP(7),
    "ISCOMPLETED" NUMBER(1),
    "ACTIVITYTYPE" VARCHAR2(50 CHAR),
    "ACTIVITYOBJECTID" NUMBER(19),
    "DATECREATED" TIMESTAMP(7),
    "ASSESSMENTID" NUMBER(19) NOT NULL,
    "LEVELACHIEVEDID" NUMBER(19),
    "ACTIVITYID" NUMBER(19) NOT NULL,
    "ISDELETED" NUMBER(1),
    "VERSION" NUMBER(19),
    PRIMARY KEY ("USERID", "ASSESSMENTID", "ACTIVITYID")
);
