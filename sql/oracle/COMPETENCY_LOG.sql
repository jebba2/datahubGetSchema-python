-- Data set: Competency Log
-- Source: https://community.d2l.com/brightspace/kb/articles/4754-competency-data-sets#competency-log
CREATE TABLE "COMPETENCY_LOG" (
    "COMPETENCYLOGID" NUMBER(19) NOT NULL,
    "LOGTYPEID" NUMBER(10),
    "LOGTYPENAME" VARCHAR2(19 CHAR),
    "OBJECTID" NUMBER(19),
    "OBJECTTYPEID" NUMBER(10),
    "OBJECTTYPENAME" VARCHAR2(18 CHAR),
    "OBJECTVERSION" NUMBER(10),
    "LOGDATETIME" TIMESTAMP(7),
    "MODIFIEDBY" NUMBER(19),
    "INDIRECTOBJECTID" NUMBER(19),
    "INDIRECTOBJECTTYPENAME" VARCHAR2(18 CHAR),
    "INDIRECTOBJECTTYPEID" NUMBER(10),
    "INDIRECTOBJECTVERSION" NUMBER(10),
    PRIMARY KEY ("COMPETENCYLOGID")
);
CREATE INDEX "IX_COMPETENCY_LOG_OBJECTID" ON "COMPETENCY_LOG" ("OBJECTID");
CREATE INDEX "IX_COMPETENCY_LOG_MODIFIEDBY" ON "COMPETENCY_LOG" ("MODIFIEDBY");
