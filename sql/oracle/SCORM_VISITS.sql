-- Data set: SCORM Visits
-- Source: https://community.d2l.com/brightspace/kb/articles/4536-scorm-data-sets#scorm-visits
CREATE TABLE "SCORM_VISITS" (
    "VISITID" VARCHAR2(36 CHAR) NOT NULL,
    "SCORMOBJECTID" VARCHAR2(36 CHAR),
    "USERID" NUMBER(10),
    "ORGUNITID" NUMBER(10),
    "FIRSTACCESSDATE" TIMESTAMP(7),
    "LASTACCESSDATE" TIMESTAMP(7),
    "COMPLETEDDATE" TIMESTAMP(7),
    "COMPLETION" VARCHAR2(100 CHAR),
    "SUCCESS" VARCHAR2(100 CHAR),
    "SCORE" BINARY_DOUBLE,
    "TIMESPENT" NUMBER(10),
    "PROGRESS" BINARY_DOUBLE,
    "LASTMODIFIED" TIMESTAMP(7),
    PRIMARY KEY ("VISITID")
);
CREATE INDEX "IX_SCORM_VISITS_SCORMOBJECTID" ON "SCORM_VISITS" ("SCORMOBJECTID");
CREATE INDEX "IX_SCORM_VISITS_USERID" ON "SCORM_VISITS" ("USERID");
CREATE INDEX "IX_SCORM_VISITS_ORGUNITID" ON "SCORM_VISITS" ("ORGUNITID");
