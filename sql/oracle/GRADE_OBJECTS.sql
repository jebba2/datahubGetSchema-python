-- Data set: Grade Objects
-- Source: https://community.d2l.com/brightspace/kb/articles/4527-grades-data-sets#grade-objects
CREATE TABLE "GRADE_OBJECTS" (
    "GRADEOBJECTID" NUMBER(10) NOT NULL,
    "ORGUNITID" NUMBER(10),
    "PARENTGRADEOBJECTID" NUMBER(10),
    "NAME" VARCHAR2(128 CHAR),
    "TYPENAME" VARCHAR2(50 CHAR),
    "STARTDATE" TIMESTAMP(7),
    "ENDDATE" TIMESTAMP(7),
    "ISAUTOPOINTED" NUMBER(1),
    "ISFORMULA" NUMBER(1),
    "ISBONUS" NUMBER(1),
    "MAXPOINTS" NUMBER(19,9),
    "CANEXCEEDMAXGRADE" NUMBER(1),
    "EXCLUDEFROMFINALGRADECALC" NUMBER(1),
    "GRADESCHEMEID" NUMBER(19),
    "WEIGHT" NUMBER(19,9),
    "NUMLOWESTGRADESTODROP" NUMBER(10),
    "NUMHIGHESTGRADESTODROP" NUMBER(10),
    "WEIGHTDISTRIBUTIONTYPE" VARCHAR2(8 CHAR),
    "CREATEDDATE" TIMESTAMP(7),
    "TOOLNAME" VARCHAR2(50 CHAR),
    "ASSOCIATEDTOOLITEMID" NUMBER(19),
    "LASTMODIFIED" TIMESTAMP(7),
    "SHORTNAME" VARCHAR2(128 CHAR),
    "GRADEOBJECTTYPEID" NUMBER(10),
    "SORTORDER" NUMBER(10),
    "ISDELETED" NUMBER(1),
    "DELETEDDATE" TIMESTAMP(7),
    "DELETEDBYUSERID" NUMBER(10),
    "RESULTID" NUMBER(10),
    "TOOLID" NUMBER(10),
    "VERSION" NUMBER(10),
    PRIMARY KEY ("GRADEOBJECTID")
);
CREATE INDEX "IX_GRADE_OBJECTS_ORGUNITID" ON "GRADE_OBJECTS" ("ORGUNITID");
CREATE INDEX "IX_GRADE_OBJECTS_PARENTGRADEOBJECTID" ON "GRADE_OBJECTS" ("PARENTGRADEOBJECTID");
CREATE INDEX "IX_GRADE_OBJECTS_DELETEDBYUSERID" ON "GRADE_OBJECTS" ("DELETEDBYUSERID");
CREATE INDEX "IX_GRADE_OBJECTS_RESULTID" ON "GRADE_OBJECTS" ("RESULTID");
