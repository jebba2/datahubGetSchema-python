-- Data set: Discussion Topics
-- Source: https://community.d2l.com/brightspace/kb/articles/4525-discussions-data-sets#discussion-topics
CREATE TABLE "DISCUSSION_TOPICS" (
    "ORGUNITID" NUMBER(10),
    "TOPICID" NUMBER(19) NOT NULL,
    "FORUMID" NUMBER(19),
    "NAME" VARCHAR2(1000 CHAR),
    "DESCRIPTION" VARCHAR2(1000 CHAR),
    "MUSTPOSTTOPARTICIPATE" NUMBER(1),
    "ALLOWANON" NUMBER(1),
    "ISHIDDEN" NUMBER(1),
    "REQUIRESAPPROVAL" NUMBER(1),
    "LASTPOSTDATE" TIMESTAMP(7),
    "LASTPOSTUSERID" NUMBER(19),
    "NUMVIEWS" NUMBER(19),
    "SORTORDER" NUMBER(10),
    "ISDELETED" NUMBER(1),
    "DELETEDDATE" TIMESTAMP(7),
    "DELETEDBYUSERID" NUMBER(10),
    "GRADEITEMID" NUMBER(10),
    "SCOREOUTOF" BINARY_DOUBLE,
    "SCORECALCULATIONMETHOD" VARCHAR2(19 CHAR),
    "INCLUDENONSCOREDVALUES" NUMBER(1),
    "VERSION" NUMBER(19),
    "RESULTID" NUMBER(10),
    "STARTDATE" TIMESTAMP(7),
    "STARTDATEAVAILABILITYTYPE" NUMBER(5),
    "ENDDATE" TIMESTAMP(7),
    "ENDDATEAVAILABILITYTYPE" NUMBER(5),
    "AIUTILIZATION" NUMBER(10),
    "DUEDATE" TIMESTAMP(7),
    PRIMARY KEY ("TOPICID")
);
CREATE INDEX "IX_DISCUSSION_TOPICS_ORGUNITID" ON "DISCUSSION_TOPICS" ("ORGUNITID");
CREATE INDEX "IX_DISCUSSION_TOPICS_FORUMID" ON "DISCUSSION_TOPICS" ("FORUMID");
CREATE INDEX "IX_DISCUSSION_TOPICS_DELETEDBYUSERID" ON "DISCUSSION_TOPICS" ("DELETEDBYUSERID");
CREATE INDEX "IX_DISCUSSION_TOPICS_GRADEITEMID" ON "DISCUSSION_TOPICS" ("GRADEITEMID");
CREATE INDEX "IX_DISCUSSION_TOPICS_RESULTID" ON "DISCUSSION_TOPICS" ("RESULTID");
