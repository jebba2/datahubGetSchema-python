-- Data set: Grade Book Settings (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4527-grades-data-sets#grade-book-settings
CREATE TABLE "GRADE_BOOK_SETTINGS_LOAD" (
    "ORGUNITID" NUMBER(10) NOT NULL,
    "GRADESCHEMEID" NUMBER(19) NOT NULL,
    "GRADINGSYSTEM" VARCHAR2(8 CHAR),
    "UNGRADEDITEMS" VARCHAR2(25 CHAR),
    "ISADJUSTEDFINALGRADERELEASED" NUMBER(1),
    "ISCALCULATEDFINALGRADERELEASED" NUMBER(1),
    "LASTMODIFIED" TIMESTAMP(7),
    PRIMARY KEY ("ORGUNITID", "GRADESCHEMEID")
);
