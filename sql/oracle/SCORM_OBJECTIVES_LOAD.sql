-- Data set: SCORM Objectives (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4536-scorm-data-sets#scorm-objectives
CREATE TABLE "SCORM_OBJECTIVES_LOAD" (
    "OBJECTIVEID" VARCHAR2(36 CHAR) NOT NULL,
    "SCORMOBJECTID" VARCHAR2(36 CHAR),
    "OBJECTIVETYPE" VARCHAR2(100 CHAR),
    "ACTIVITYID" VARCHAR2(36 CHAR),
    "INTERNALID" VARCHAR2(255 CHAR),
    "ISPRIMARY" NUMBER(1),
    "DESCRIPTION" VARCHAR2(250 CHAR),
    "SCOREMIN" BINARY_DOUBLE,
    "SCOREMAX" BINARY_DOUBLE,
    "LASTMODIFIED" TIMESTAMP(7),
    PRIMARY KEY ("OBJECTIVEID")
);
