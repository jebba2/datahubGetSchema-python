-- Data set: SCORM Activity Attempts (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4536-scorm-data-sets#scorm-activity-attempts
CREATE TABLE "SCORM_ACTIVITY_ATTEMPTS_LOAD" (
    "VISITID" VARCHAR2(36 CHAR) NOT NULL,
    "ACTIVITYID" VARCHAR2(36 CHAR) NOT NULL,
    "ATTEMPTNUMBER" NUMBER(10) NOT NULL,
    "COMPLETION" VARCHAR2(100 CHAR),
    "SUCCESS" VARCHAR2(100 CHAR),
    "SCORE" BINARY_DOUBLE,
    "SCORERAW" BINARY_DOUBLE,
    "TIMESPENT" BINARY_DOUBLE,
    "PROGRESS" BINARY_DOUBLE,
    "LASTMODIFIED" TIMESTAMP(7),
    PRIMARY KEY ("VISITID", "ACTIVITYID", "ATTEMPTNUMBER")
);
