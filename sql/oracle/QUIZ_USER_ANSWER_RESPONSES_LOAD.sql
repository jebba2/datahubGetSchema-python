-- Data set: Quiz User Answer Responses (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4532-quizzes-data-sets#quiz-user-answer-responses
CREATE TABLE "QUIZ_USER_ANSWER_RESPONSES_LOAD" (
    "ATTEMPTID" NUMBER(19) NOT NULL,
    "ATTEMPTNUMBER" NUMBER(10),
    "QUESTIONID" NUMBER(19) NOT NULL,
    "QUESTIONVERSIONID" NUMBER(19) NOT NULL,
    "ANSWERID" NUMBER(19) NOT NULL,
    "SORTORDER" NUMBER(10),
    "ISCORRECT" NUMBER(1),
    "USERSELECTION" NUMBER(19),
    "USERANSWER" VARCHAR2(1000 CHAR),
    "FILESETID" NUMBER(19),
    "LASTMODIFIED" TIMESTAMP(7),
    "ISDELETED" NUMBER(1),
    PRIMARY KEY ("ATTEMPTID", "QUESTIONID", "QUESTIONVERSIONID", "ANSWERID")
);
