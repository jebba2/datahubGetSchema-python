    "ENDDATE" TIMESTAMP(7),
    "DUEDATE" TIMESTAMP(7),
    "ISRESTRICTED" NUMBER(1),
    "ISDELETED" NUMBER(1),
    "TURNITINENABLED" NUMBER(1),
    "ISHIDDEN" NUMBER(1),
    "SORTORDER" NUMBER(10),
    "SUBMISSIONTYPE" VARCHAR2(18 CHAR),
    "COMPLETIONTYPE" VARCHAR2(27 CHAR),
    "RESULTID" NUMBER(10),
    "CATEGORYID" NUMBER(19),
    "VERSION" NUMBER(19),
    "STARTDATEAVAILABILITYTYPE" NUMBER(5),
    "ENDDATEAVAILABILITYTYPE" NUMBER(5),
    "AIUTILIZATION" NUMBER(10),
