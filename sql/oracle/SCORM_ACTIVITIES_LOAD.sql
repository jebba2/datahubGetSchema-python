-- Data set: SCORM Activities (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4536-scorm-data-sets#scorm-activities
CREATE TABLE "SCORM_ACTIVITIES_LOAD" (
    "ACTIVITYID" VARCHAR2(36 CHAR) NOT NULL,
    "SCORMOBJECTID" VARCHAR2(36 CHAR),
    "PARENTACTIVITYID" VARCHAR2(36 CHAR),
    "NUMCHILDREN" NUMBER(10),
    "INTERNALID" VARCHAR2(255 CHAR),
    "TITLE" VARCHAR2(200 CHAR),
    "COMPLETIONTHRESHOLD" BINARY_DOUBLE,
    "PASSINGSCORE" BINARY_DOUBLE,
    "PASSINGSCOREUSED" NUMBER(1),
    "SCOREMIN" BINARY_DOUBLE,
    "SCOREMAX" BINARY_DOUBLE,
    "LASTMODIFIED" TIMESTAMP(7),
    PRIMARY KEY ("ACTIVITYID")
);
