-- Data set: Award Objects (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4520-awards-data-sets#award-objects
CREATE TABLE "AWARD_OBJECTS_LOAD" (
    "AWARDID" NUMBER(19) NOT NULL,
    "NAME" VARCHAR2(256 CHAR),
    "AWARDTYPEID" NUMBER(10),
    "TYPE" VARCHAR2(128 CHAR),
    "DESCRIPTION" VARCHAR2(512 CHAR),
    "EXPIRYCALCULATIONTYPE" VARCHAR2(128 CHAR),
    "EXPIRYNOTIFICATIONTYPE" VARCHAR2(128 CHAR),
    "EXPIRYDATE" TIMESTAMP(7),
    "IMAGEPATH" VARCHAR2(1000 CHAR),
    "CREATEDBYUSERID" NUMBER(19),
    "LASTMODIFIED" TIMESTAMP(7),
    "ISDELETED" NUMBER(1),
    "CRITERIA" VARCHAR2(1000 CHAR),
    PRIMARY KEY ("AWARDID")
);
