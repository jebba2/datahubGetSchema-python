-- Data set: Calendar Events (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4521-calendar-data-sets#calendar-events
CREATE TABLE "CALENDAR_EVENTS_LOAD" (
    "SCHEDULEID" NUMBER(19) NOT NULL,
    "ORGUNITID" NUMBER(19),
    "USERID" NUMBER(19),
    "TITLE" VARCHAR2(256 CHAR),
    "STARTDATE" TIMESTAMP(7),
    "ENDDATE" TIMESTAMP(7),
    "TIMEZONEIDENTIFIER" VARCHAR2(256 CHAR),
    "ISALLDAYEVENT" NUMBER(1),
    "RECURRENCETYPE" VARCHAR2(7 CHAR),
    "RECURRENCEINTERVAL" NUMBER(10),
    "CREATEDBYUSERID" NUMBER(10),
    "LASTMODIFIED" TIMESTAMP(7),
    "EVENTOBJECTTYPENAME" VARCHAR2(200 CHAR),
    "OBJECTLOOKUPID1" NUMBER(19),
    "OBJECTLOOKUPID2" NUMBER(19),
    PRIMARY KEY ("SCHEDULEID")
);
