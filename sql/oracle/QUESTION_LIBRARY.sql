-- Data set: Question Library
-- Source: https://community.d2l.com/brightspace/kb/articles/4531-questions-data-sets#question-library
CREATE TABLE "QUESTION_LIBRARY" (
    "QUESTIONID" NUMBER(19) NOT NULL,
    "QUESTIONVERSIONID" NUMBER(19) NOT NULL,
    "ISAUTOGRADED" NUMBER(1),
    "TEMPLATETYPEID" NUMBER(10),
    "QUESTIONTYPE" VARCHAR2(28 CHAR),
    "NAME" VARCHAR2(256 CHAR),
    "QUESTION" VARCHAR2(1000 CHAR),
    "COMMENT" VARCHAR2(1000 CHAR),
    "ANSWERKEY" VARCHAR2(1000 CHAR),
    "CREATIONDATE" TIMESTAMP(7),
    "VERSION" NUMBER(19),
    "ALLOWSATTACHMENTS" NUMBER(1),
    "AIUTILIZATION" NUMBER(10),
    PRIMARY KEY ("QUESTIONID", "QUESTIONVERSIONID")
);
