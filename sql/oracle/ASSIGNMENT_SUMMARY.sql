-- Data set: Assignment Summary
-- Source: https://community.d2l.com/brightspace/kb/articles/4767-assignments-data-sets#assignment-summary
CREATE TABLE "ASSIGNMENT_SUMMARY" (
    "DROPBOXID" NUMBER(19) NOT NULL,
    "ORGUNITID" NUMBER(10),
    "NAME" VARCHAR2(128 CHAR),
    "CATEGORY" VARCHAR2(128 CHAR),
    "TYPE" VARCHAR2(10 CHAR),
    "GRADEITEMID" NUMBER(19),
    "POSSIBLESCORE" NUMBER(19,9),
    "STARTDATE" TIMESTAMP(7),
    "ENDDATE" TIMESTAMP(7),
    "DUEDATE" TIMESTAMP(7),
    "ISRESTRICTED" NUMBER(1),
    "ISDELETED" NUMBER(1),
    "TURNITINENABLED" NUMBER(1),
    "ISHIDDEN" NUMBER(1),
    "SORTORDER" NUMBER(10),
    "SUBMISSIONTYPE" VARCHAR2(18 CHAR),
    "COMPLETIONTYPE" VARCHAR2(27 CHAR),
    "RESULTID" NUMBER(10),
    "CATEGORYID" NUMBER(19),
    "VERSION" NUMBER(19),
    "STARTDATEAVAILABILITYTYPE" NUMBER(5),
    "ENDDATEAVAILABILITYTYPE" NUMBER(5),
    "AIUTILIZATION" NUMBER(10),
    "INSTRUCTIONS" CLOB,
    PRIMARY KEY ("DROPBOXID")
);
CREATE INDEX "IX_ASSIGNMENT_SUMMARY_ORGUNITID" ON "ASSIGNMENT_SUMMARY" ("ORGUNITID");
CREATE INDEX "IX_ASSIGNMENT_SUMMARY_GRADEITEMID" ON "ASSIGNMENT_SUMMARY" ("GRADEITEMID");
CREATE INDEX "IX_ASSIGNMENT_SUMMARY_RESULTID" ON "ASSIGNMENT_SUMMARY" ("RESULTID");
