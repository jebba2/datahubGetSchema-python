-- Data set: Awards Issued (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4520-awards-data-sets#awards-issued
CREATE TABLE "AWARDS_ISSUED_LOAD" (
    "AWARDID" NUMBER(19),
    "ORGUNITID" NUMBER(19),
    "USERID" NUMBER(19),
    "ISSUEDBY" NUMBER(10),
    "ISSUEDATE" TIMESTAMP(7),
    "EXPIRYDATE" TIMESTAMP(7),
    "ISSUEDID" NUMBER(19) NOT NULL,
    "CRITERIA" VARCHAR2(1000 CHAR),
    "EVIDENCE" VARCHAR2(1000 CHAR),
    "REVOKEDDATE" TIMESTAMP(7),
    "REVOKEDREASON" VARCHAR2(1000 CHAR),
    "REVOKEDBY" NUMBER(19),
    "LASTMODIFIEDBY" NUMBER(19),
    "LASTMODIFIEDDATE" TIMESTAMP(7),
    "VERSION" NUMBER(19),
    "CERTIFICATEID" VARCHAR2(12 CHAR),
    PRIMARY KEY ("ISSUEDID")
);
