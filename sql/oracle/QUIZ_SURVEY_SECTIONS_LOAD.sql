-- Data set: Quiz Survey Sections (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4532-quizzes-data-sets#quiz-survey-sections
CREATE TABLE "QUIZ_SURVEY_SECTIONS_LOAD" (
    "COLLECTIONID" NUMBER(19),
    "SECTIONID" NUMBER(19) NOT NULL,
    "NAME" VARCHAR2(256 CHAR),
    "NAMEISDISPLAYED" NUMBER(1),
    "ISQUESTIONPOOL" NUMBER(1),
    "SECTIONTEXT" VARCHAR2(1000 CHAR),
    "SECTIONTEXTISHTML" NUMBER(1),
    "ISSECTIONTEXTHIDDEN" NUMBER(1),
    "QUESTIONPOINTS" NUMBER(19,9),
    "NUMQUESTIONS" NUMBER(10),
    "NUMCHOICES" NUMBER(10),
    "SHUFFLE" NUMBER(1),
    "CREATIONDATE" TIMESTAMP(7),
    "CREATEDBY" NUMBER(19),
    "LASTMODIFIED" TIMESTAMP(7),
    "LASTMODIFIEDBY" NUMBER(19),
    "ISDELETED" NUMBER(1),
    "VERSION" NUMBER(19),
    PRIMARY KEY ("SECTIONID")
);
