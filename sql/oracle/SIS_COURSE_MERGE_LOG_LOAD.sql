-- Data set: SIS Course Merge Log (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/19147-sis-course-merge-data-sets#sis-course-merge-log
CREATE TABLE "SIS_COURSE_MERGE_LOG_LOAD" (
    "BATCHID" VARCHAR2(36 CHAR) NOT NULL,
    "JOBTYPE" VARCHAR2(32 CHAR),
    "STATUS" VARCHAR2(32 CHAR),
    "ORIGINALTARGETORGUNITID" NUMBER(19),
    "ORIGINALSOURCEORGUNITID" NUMBER(19) NOT NULL,
    "SOURCESYSTEMID" NUMBER(19),
    "NUMBEROFCOURSESINBATCH" NUMBER(10),
    "USERID" NUMBER(19),
    "ERRORTYPE" VARCHAR2(48 CHAR),
    "TIMESTAMP" TIMESTAMP(7) NOT NULL,
    PRIMARY KEY ("BATCHID", "ORIGINALSOURCEORGUNITID", "TIMESTAMP")
);
