-- Data set: Release Condition Objects (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4533-release-conditions-data-sets#release-condition-objects
CREATE TABLE "RELEASE_CONDITION_OBJECTS_LOAD" (
    "PREREQUISITEID" NUMBER(10) NOT NULL,
    "RESULTID" NUMBER(10) NOT NULL,
    "ORGUNITID" NUMBER(10) NOT NULL,
    "NAME" VARCHAR2(64 CHAR),
    "ISNEGATIVECONDITION" NUMBER(1),
    "PREREQUISITETOOLID" NUMBER(10),
    "ID1" NUMBER(10),
    "ID2" NUMBER(10),
    "RESULTTOOLID" NUMBER(10),
    "USESPERCENTAGE" NUMBER(1),
    "OPERATORTYPEDESC" VARCHAR2(3 CHAR),
    "VERSION" NUMBER(19),
    "GUID1" VARCHAR2(36 CHAR),
    "GUID2" VARCHAR2(36 CHAR),
    PRIMARY KEY ("PREREQUISITEID", "RESULTID", "ORGUNITID")
);
