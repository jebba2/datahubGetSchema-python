-- Data set: Outcome Details (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4796-outcomes-data-sets#outcome-details
CREATE TABLE "OUTCOME_DETAILS_LOAD" (
    "OUTCOMEID" VARCHAR2(36 CHAR) NOT NULL,
    "OUTCOMEDEFINITIONSOURCE" VARCHAR2(1000 CHAR),
    "OUTCOMEDEFINITIONID" VARCHAR2(128 CHAR),
    "PARENTOUTCOMEID" VARCHAR2(36 CHAR),
    "DESCRIPTION" VARCHAR2(1000 CHAR),
    "NOTATION" VARCHAR2(1000 CHAR),
    "CREATEDDATE" TIMESTAMP(7),
    "CREATEDBY" NUMBER(10),
    "LASTMODIFIEDDATE" TIMESTAMP(7),
    "LASTMODIFIEDBY" NUMBER(10),
    "ISDELETED" NUMBER(1),
    PRIMARY KEY ("OUTCOMEID")
);
