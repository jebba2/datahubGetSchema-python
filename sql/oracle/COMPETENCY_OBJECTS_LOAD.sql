-- Data set: Competency Objects (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4754-competency-data-sets#competency-objects
CREATE TABLE "COMPETENCY_OBJECTS_LOAD" (
    "OBJECTID" NUMBER(19) NOT NULL,
    "ORGUNITID" NUMBER(10),
    "NAME" VARCHAR2(256 CHAR),
    "TYPE" VARCHAR2(256 CHAR),
    "READYFOREVALUATION" NUMBER(1),
    "STATUS" VARCHAR2(9 CHAR),
    "DESCRIPTION" VARCHAR2(1000 CHAR),
    "NEEDREEVALUATION" NUMBER(1),
    "REEVALUATIONIFACHIEVED" NUMBER(1),
    "REEVALUATIONIFNOTACHIEVED" NUMBER(1),
    "ADDITIONALIDENTIFIER" VARCHAR2(512 CHAR),
    "ISHIDDEN" NUMBER(1),
    PRIMARY KEY ("OBJECTID")
);
