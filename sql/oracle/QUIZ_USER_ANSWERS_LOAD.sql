-- Data set: Quiz User Answers (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4532-quizzes-data-sets#quiz-user-answers
CREATE TABLE "QUIZ_USER_ANSWERS_LOAD" (
    "ATTEMPTID" NUMBER(19) NOT NULL,
    "QUESTIONID" NUMBER(19),
    "QUESTIONVERSIONID" NUMBER(19),
    "TIMECOMPLETED" TIMESTAMP(7),
    "QUESTIONNUMBER" NUMBER(10),
    "COMMENT" VARCHAR2(1000 CHAR),
    "SORTORDER" NUMBER(10),
    "SCORE" NUMBER(19,9),
    "PAGE" NUMBER(10),
    "SECTIONID" NUMBER(19),
    "OBJECTID" NUMBER(19) NOT NULL,
    "OUTOF" NUMBER(19,9),
    "TIMESTARTED" TIMESTAMP(7),
    "ISBONUS" NUMBER(1),
    "ISDELETED" NUMBER(1),
    "LASTMODIFIED" TIMESTAMP(7),
    "LASTMODIFIEDBY" NUMBER(10),
    "QUIZTIMECOMPLETED" TIMESTAMP(7),
    PRIMARY KEY ("ATTEMPTID", "OBJECTID")
);
