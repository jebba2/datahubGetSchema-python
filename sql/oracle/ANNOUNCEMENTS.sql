-- Data set: Announcements
-- Source: https://community.d2l.com/brightspace/kb/articles/4723-announcements-data-sets#announcements
CREATE TABLE "ANNOUNCEMENTS" (
    "ANNOUNCEMENTID" NUMBER(19) NOT NULL,
    "ORGUNITID" NUMBER(19),
    "TITLE" VARCHAR2(400 CHAR),
    "STARTDATE" TIMESTAMP(7),
    "ENDDATE" TIMESTAMP(7),
    "ISGLOBAL" NUMBER(1),
    "ISDRAFT" NUMBER(1),
    "NUMATTACHMENTS" NUMBER(10),
    "DELETEDDATE" TIMESTAMP(7),
    "DELETEDBYUSERID" NUMBER(10),
    "LASTMODIFIED" TIMESTAMP(7),
    "LASTMODIFIEDBY" NUMBER(10),
    "CREATEDBY" NUMBER(10),
    "ISAUTHORINFOSHOWN" NUMBER(1),
    "CREATEDDATE" TIMESTAMP(7),
    "RESULTID" NUMBER(19),
    PRIMARY KEY ("ANNOUNCEMENTID")
);
CREATE INDEX "IX_ANNOUNCEMENTS_ORGUNITID" ON "ANNOUNCEMENTS" ("ORGUNITID");
CREATE INDEX "IX_ANNOUNCEMENTS_DELETEDBYUSERID" ON "ANNOUNCEMENTS" ("DELETEDBYUSERID");
CREATE INDEX "IX_ANNOUNCEMENTS_RESULTID" ON "ANNOUNCEMENTS" ("RESULTID");
