    "LEARNINGSTANDARD" VARCHAR2(100 CHAR),
    "LASTMODIFIED" TIMESTAMP(7),
    "LASTMODIFIEDBY" NUMBER(10),
    PRIMARY KEY ("SCORMOBJECTID")
