-- Data set: Intelligent Agent Objects
-- Source: https://community.d2l.com/brightspace/kb/articles/4528-intelligent-agents-data-sets#intelligent-agent-objects
CREATE TABLE "INTELLIGENT_AGENT_OBJECTS" (
    "AGENTID" NUMBER(19) NOT NULL,
    "ORGUNITID" NUMBER(10),
    "AGENTNAME" VARCHAR2(128 CHAR),
    "DESCRIPTION" VARCHAR2(1000 CHAR),
    "ENABLED" NUMBER(1),
    "SPECIFICROLES" VARCHAR2(1000 CHAR),
    "LOGINCONDITIONENABLED" NUMBER(1),
    "LOGINCONDITIONTHRESHOLD" NUMBER(10),
    "LOGINCONDITIONTYPE" VARCHAR2(14 CHAR),
    "ACCESSCONDITIONENABLED" NUMBER(1),
    "ACCESSCONDITIONTHRESHOLD" NUMBER(10),
    "ACCESSCONDITIONTYPE" VARCHAR2(20 CHAR),
    "RESULTID" NUMBER(19),
    "REPEATTYPE" VARCHAR2(10 CHAR),
    "EMAILWHENSATISFIED" NUMBER(1),
    "ENABLESCHEDULE" NUMBER(1),
    "SCHEDULETYPE" VARCHAR2(10 CHAR),
    "SCHEDULEREPEATSEVERY" NUMBER(10),
    "STARTDATE" TIMESTAMP(7),
    "ENDDATE" TIMESTAMP(7),
    "LASTMODIFIED" TIMESTAMP(7),
    "LASTMODIFIEDBY" NUMBER(10),
    "ISDELETED" NUMBER(1),
    PRIMARY KEY ("AGENTID")
);
CREATE INDEX "IX_INTELLIGENT_AGENT_OBJECTS_ORGUNITID" ON "INTELLIGENT_AGENT_OBJECTS" ("ORGUNITID");
CREATE INDEX "IX_INTELLIGENT_AGENT_OBJECTS_RESULTID" ON "INTELLIGENT_AGENT_OBJECTS" ("RESULTID");
CREATE INDEX "IX_INTELLIGENT_AGENT_OBJECTS_LASTMODIFIEDBY" ON "INTELLIGENT_AGENT_OBJECTS" ("LASTMODIFIEDBY");
