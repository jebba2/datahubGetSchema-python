-- Data set: Users
-- Source: https://community.d2l.com/brightspace/kb/articles/4740-users-data-sets#users
CREATE TABLE "USERS" (
    "USERID" NUMBER(10) NOT NULL,
    "USERNAME" VARCHAR2(270 CHAR),
    "ORGDEFINEDID" VARCHAR2(256 CHAR),
    "FIRSTNAME" VARCHAR2(64 CHAR),
    "MIDDLENAME" VARCHAR2(64 CHAR),
    "LASTNAME" VARCHAR2(64 CHAR),
    "ISACTIVE" NUMBER(1),
    "EXTERNALEMAIL" VARCHAR2(256 CHAR),
    "CREATIONDATE" TIMESTAMP(7),
    "VERSION" NUMBER(19),
    "ORGROLEID" NUMBER(10),
    "DATEDELETED" TIMESTAMP(7),
    PRIMARY KEY ("USERID")
);
