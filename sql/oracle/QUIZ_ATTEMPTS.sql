-- Data set: Quiz Attempts
-- Source: https://community.d2l.com/brightspace/kb/articles/4532-quizzes-data-sets#quiz-attempts
CREATE TABLE "QUIZ_ATTEMPTS" (
    "ATTEMPTID" NUMBER(19) NOT NULL,
    "QUIZID" NUMBER(19),
    "USERID" NUMBER(10),
    "ORGUNITID" NUMBER(10),
    "ATTEMPTNUMBER" NUMBER(10),
    "TIMESTARTED" TIMESTAMP(7),
    "TIMECOMPLETED" TIMESTAMP(7),
    "SCORE" NUMBER(19,9),
    "ISGRADED" NUMBER(1),
    "OLDATTEMPTNUMBER" NUMBER(10),
    "ISDELETED" NUMBER(1),
    "POSSIBLESCORE" NUMBER(19,9),
    "ISRETAKEINCORRECTONLY" NUMBER(1),
    "DUEDATE" TIMESTAMP(7),
    "TIMELIMIT" NUMBER(10),
    "TIMELIMITENFORCED" NUMBER(1),
    "TIMELIMITEXCEEDEDBEHAVIOUR" VARCHAR2(128 CHAR),
    "ISSYNCHRONOUS" NUMBER(1),
    "DEDUCTIONPERCENTAGE" NUMBER(10),
    "VERSION" NUMBER(19),
    PRIMARY KEY ("ATTEMPTID")
);
CREATE INDEX "IX_QUIZ_ATTEMPTS_QUIZID" ON "QUIZ_ATTEMPTS" ("QUIZID");
CREATE INDEX "IX_QUIZ_ATTEMPTS_USERID" ON "QUIZ_ATTEMPTS" ("USERID");
CREATE INDEX "IX_QUIZ_ATTEMPTS_ORGUNITID" ON "QUIZ_ATTEMPTS" ("ORGUNITID");
