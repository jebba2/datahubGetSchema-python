-- Data set: Portfolio Evidence Objects (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4530-portfolio-data-sets#portfolio-evidence-objects
CREATE TABLE "PORTFOLIO_EVIDENCE_OBJECTS_LOAD" (
    "EVIDENCEID" VARCHAR2(36 CHAR) NOT NULL,
    "OWNERID" NUMBER(10),
    "ORGUNITID" NUMBER(10),
    "EVIDENCETYPE" VARCHAR2(30 CHAR),
    "TITLE" VARCHAR2(1000 CHAR),
    "ISAPPROVED" NUMBER(1),
    "ISSPOTLIGHTED" NUMBER(1),
    "ISSHAREDTOPARENTS" NUMBER(1),
    "ISDELETED" NUMBER(1),
    "ISRECOVERABLEBYINSTRUCTOR" NUMBER(1),
    "LASTMODIFIED" TIMESTAMP(7),
    "LASTMODIFIEDBY" NUMBER(10),
    "ISSHAREDWITHINSTRUCTOR" NUMBER(1),
    "DATESHAREDWITHINSTRUCTOR" TIMESTAMP(7),
    PRIMARY KEY ("EVIDENCEID")
);
