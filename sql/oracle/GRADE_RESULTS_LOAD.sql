-- Data set: Grade Results (staging table)
-- Source: https://community.d2l.com/brightspace/kb/articles/4527-grades-data-sets#grade-results
CREATE TABLE "GRADE_RESULTS_LOAD" (
    "GRADEOBJECTID" NUMBER(10) NOT NULL,
    "ORGUNITID" NUMBER(10) NOT NULL,
    "USERID" NUMBER(10) NOT NULL,
    "POINTSNUMERATOR" NUMBER(19,9),
    "POINTSDENOMINATOR" NUMBER(19,9),
    "WEIGHTEDNUMERATOR" NUMBER(19,9),
    "WEIGHTEDDENOMINATOR" NUMBER(19,9),
    "ISRELEASED" NUMBER(1),
    "ISDROPPED" NUMBER(1),
    "LASTMODIFIED" TIMESTAMP(7),
    "LASTMODIFIEDBY" NUMBER(10),
    "COMMENTS" VARCHAR2(1000 CHAR),
    "PRIVATECOMMENTS" VARCHAR2(1000 CHAR),
    "GRADETEXT" VARCHAR2(50 CHAR),
    "GRADERELEASEDDATE" TIMESTAMP(7),
    "VERSION" NUMBER(19),
    "ISDELETED" NUMBER(1),
    PRIMARY KEY ("GRADEOBJECTID", "ORGUNITID", "USERID")
);
