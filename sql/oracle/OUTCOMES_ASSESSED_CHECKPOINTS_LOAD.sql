CREATE TABLE "OUTCOMES_ASSESSED_CHECKPOINTS_LOAD" (
    "CHECKPOINTID" VARCHAR2(36 CHAR) NOT NULL,
    "DEMONSTRATIONID" VARCHAR2(36 CHAR) NOT NULL,
    "FEEDBACK" VARCHAR2(1000 CHAR),
    "CONFIGDECAYRATE" NUMBER(10),
    "CONFIGAGGREGATIONMETHOD" NUMBER(10),
    "CONFIGINCLUDEDACTIVITIES" NUMBER(10),
    "CONFIGMULTIPLEATTEMPTSTRATEGY" NUMBER(10),
    "CONFIGRECENTLYASSESSEDACTIVITYCOUNT" NUMBER(10),
    "CONFIGTIEBREAKER" NUMBER(10),
    "LASTMODIFIEDDATE" TIMESTAMP(7),
    "LASTMODIFIEDBY" NUMBER(10),
    "ISDELETED" NUMBER(1),
    "HASMETACHIEVEMENTTHRESHOLD" NUMBER(1),
    "ACHIEVEDLEVELID" VARCHAR2(36 CHAR),
    PRIMARY KEY ("CHECKPOINTID", "DEMONSTRATIONID")
