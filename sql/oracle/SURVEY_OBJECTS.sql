-- Data set: Survey Objects
-- Source: https://community.d2l.com/brightspace/kb/articles/4538-surveys-data-sets#survey-objects
CREATE TABLE "SURVEY_OBJECTS" (
    "SURVEYID" NUMBER(19) NOT NULL,
    "SURVEYNAME" VARCHAR2(1000 CHAR),
    "CATEGORYID" NUMBER(19),
    "ORGUNITID" NUMBER(10),
    "DESCRIPTION" VARCHAR2(1000 CHAR),
    "DESCRIPTIONENABLED" NUMBER(1),
    "HASINSTANTFEEDBACK" NUMBER(1),
    "ISANONYMOUS" NUMBER(1),
    "ISVISIBLE" NUMBER(1),
    "SUBMISSIONMESSAGE" VARCHAR2(1000 CHAR),
    "FOOTER" VARCHAR2(1000 CHAR),
    "FOOTERISDISPLAYED" NUMBER(1),
    "STARTDATE" TIMESTAMP(7),
    "ENDDATE" TIMESTAMP(7),
    "DISPLAYINCALENDAR" NUMBER(1),
    "RESULTID" NUMBER(19),
    "ATTEMPTSALLOWED" NUMBER(10),
    "SORTORDER" NUMBER(10),
    "CREATEDBY" NUMBER(10),
    "ISDELETED" NUMBER(1),
    "LASTMODIFIED" TIMESTAMP(7),
    "LASTMODIFIEDBY" NUMBER(10),
    "VERSION" NUMBER(19),
    "CATEGORYNAME" VARCHAR2(256 CHAR),
    PRIMARY KEY ("SURVEYID")
);
CREATE INDEX "IX_SURVEY_OBJECTS_ORGUNITID" ON "SURVEY_OBJECTS" ("ORGUNITID");
CREATE INDEX "IX_SURVEY_OBJECTS_CREATEDBY" ON "SURVEY_OBJECTS" ("CREATEDBY");
CREATE INDEX "IX_SURVEY_OBJECTS_LASTMODIFIEDBY" ON "SURVEY_OBJECTS" ("LASTMODIFIEDBY");
