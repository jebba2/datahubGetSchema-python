-- Data set: Discussion Forums
-- Source: https://community.d2l.com/brightspace/kb/articles/4525-discussions-data-sets#discussion-forums
CREATE TABLE "DISCUSSION_FORUMS" (
    "ORGUNITID" NUMBER(10),
    "FORUMID" NUMBER(19) NOT NULL,
    "NAME" VARCHAR2(400 CHAR),
    "DESCRIPTION" VARCHAR2(1000 CHAR),
    "MUSTPOSTTOPARTICIPATE" NUMBER(1),
    "ALLOWANON" NUMBER(1),
    "ISHIDDEN" NUMBER(1),
    "REQUIRESAPPROVAL" NUMBER(1),
    "SORTORDER" NUMBER(10),
    "ISDELETED" NUMBER(1),
    "DELETEDDATE" TIMESTAMP(7),
    "DELETEDBYUSERID" NUMBER(10),
    "RESULTID" NUMBER(10),
    "STARTDATE" TIMESTAMP(7),
    "STARTDATEAVAILABILITYTYPE" NUMBER(5),
    "ENDDATE" TIMESTAMP(7),
    "ENDDATEAVAILABILITYTYPE" NUMBER(5),
    "VERSION" NUMBER(19),
    PRIMARY KEY ("FORUMID")
);
CREATE INDEX "IX_DISCUSSION_FORUMS_ORGUNITID" ON "DISCUSSION_FORUMS" ("ORGUNITID");
CREATE INDEX "IX_DISCUSSION_FORUMS_DELETEDBYUSERID" ON "DISCUSSION_FORUMS" ("DELETEDBYUSERID");
CREATE INDEX "IX_DISCUSSION_FORUMS_RESULTID" ON "DISCUSSION_FORUMS" ("RESULTID");
