    "LTILINKID" NUMBER(19),
    "DEPLOYMENTID" VARCHAR2(36 CHAR),
    "CLIENTID" VARCHAR2(36 CHAR),
    "TOOLPROVIDERID" VARCHAR2(300 CHAR),
    "CONTENTTOPICID" NUMBER(19),
    "PARENTMODULEID" NUMBER(19),
    "PLACEMENT" VARCHAR2(10 CHAR),
    "MESSAGEVERSION" VARCHAR2(10 CHAR),
    "REQUESTTYPE" VARCHAR2(30 CHAR),
    PRIMARY KEY ("LTILAUNCHID")
