-- Data set: Virtual Classroom Usage
-- Source: https://community.d2l.com/brightspace/kb/articles/4541-virtual-classroom-data-sets#virtual-classroom-usage
CREATE TABLE "VIRTUAL_CLASSROOM_USAGE" (
    "ORGUNITID" NUMBER(10),
    "COURSENAME" VARCHAR2(255 CHAR),
    "MEETINGID" VARCHAR2(36 CHAR) NOT NULL,
    "MEETINGNAME" VARCHAR2(255 CHAR),
    "CREATIONUSERID" NUMBER(10),
    "CREATIONDATE" TIMESTAMP(7),
    "SCHEDULEDDATE" TIMESTAMP(7),
    "SCHEDULEDDURATION" NUMBER(10),
    "ISPUBLISHED" NUMBER(1),
    "EXTERNALLINKSENABLED" NUMBER(1),
    "WHOLECLASSINVITED" NUMBER(1),
    "ISCANCELLED" NUMBER(1),
    "STARTDATETIME" TIMESTAMP(7),
    "ENDDATETIME" TIMESTAMP(7),
    "ISRECORDED" NUMBER(1),
    PRIMARY KEY ("MEETINGID")
);
CREATE INDEX "IX_VIRTUAL_CLASSROOM_USAGE_ORGUNITID" ON "VIRTUAL_CLASSROOM_USAGE" ("ORGUNITID");
CREATE INDEX "IX_VIRTUAL_CLASSROOM_USAGE_CREATIONUSERID" ON "VIRTUAL_CLASSROOM_USAGE" ("CREATIONUSERID");
